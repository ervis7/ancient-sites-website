-- Imported catalog rows are starter data, not user additions, so they earn no points.
create or replace function public.award_place_points()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  awarded_action text;
begin
  if new.catalog_id is not null then
    return new;
  end if;

  if tg_op = 'INSERT' then
    awarded_action := 'place_added';
  elsif new.visited = true and old.visited = false then
    awarded_action := 'place_visited';
  else
    return new;
  end if;

  update public.profiles
  set points = points + 5
  where id = new.user_id;

  insert into public.point_events (
    user_id, place_id, action_type, points, place_name
  ) values (
    new.user_id, new.id, awarded_action, 5, new.name
  );
  return new;
end;
$$;

create or replace function public.seed_ancient_catalog_for_user(target_user_id uuid)
returns void
language sql
security definer
set search_path = ''
as $$
  insert into public.places (
    user_id, catalog_id, nomos_id, name, location, latitude, longitude, visibility
  )
  select
    target_user_id, catalog.catalog_id, catalog.nomos_id, catalog.name,
    catalog.location, catalog.latitude, catalog.longitude, 'public'
  from public.ancient_place_catalog catalog
  on conflict (user_id, catalog_id) where catalog_id is not null do nothing;
$$;

create or replace function public.seed_ancient_catalog_on_signup()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.seed_ancient_catalog_for_user(new.id);
  return new;
